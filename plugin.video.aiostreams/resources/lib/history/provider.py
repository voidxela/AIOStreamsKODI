"""History provider contract.  Providers never expose Kodi or storage rows."""
from typing import List, Optional, Protocol

from .models import (HistoryMediaRef, HistoryState, NextUpEntry, PlaybackEvent,
                     ProviderResult, ProviderStatus, ResumePoint)


class HistoryProvider(Protocol):
    provider_id: str

    def status(self) -> ProviderStatus: ...
    def get_state(self, media: HistoryMediaRef) -> HistoryState: ...
    def get_resume(self, media: HistoryMediaRef) -> Optional[ResumePoint]: ...
    def handle_playback(self, event: PlaybackEvent) -> ProviderResult: ...
    def mark_watched(self, media: HistoryMediaRef, watched: bool) -> ProviderResult: ...
    def clear_progress(self, media: HistoryMediaRef) -> ProviderResult: ...
    def list_next_up(self, limit: Optional[int] = None) -> List[NextUpEntry]: ...
    def set_next_up_hidden(self, show: HistoryMediaRef, hidden: bool) -> ProviderResult: ...
    def sync(self, force: bool = False) -> ProviderResult: ...
